import { DocFormat } from './document-policy'

/** Detect the real format from the file's leading bytes. Never trust the extension or Content-Type. */
export function sniffFormat(buf: Buffer): DocFormat | null {
  if (buf.length >= 5 && buf.subarray(0, 5).toString('latin1') === '%PDF-') return 'pdf'
  if (
    buf.length >= 8 &&
    buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47 &&
    buf[4] === 0x0d && buf[5] === 0x0a && buf[6] === 0x1a && buf[7] === 0x0a
  ) {
    return 'png'
  }
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'jpg'
  return null
}

/** PDFs that carry auto-run scripts or launch actions are refused outright. */
export function pdfHasActiveContent(buf: Buffer): boolean {
  return /\/(JavaScript|Launch)\b|\/JS\b/.test(buf.toString('latin1'))
}

/** Keep only a safe display name; the stored object key is generated by the server. */
export function sanitizeFilename(name: string | undefined): string {
  const base = (name ?? 'document').split(/[\\/]/).pop() ?? 'document'
  const cleaned = base.replace(/[\u0000-\u001f\u007f<>:"|?*]/g, '').replace(/^\.+/, '').trim()
  return (cleaned || 'document').slice(0, 120)
}

export const EXTENSION: Record<DocFormat, string> = { pdf: 'pdf', jpg: 'jpg', png: 'png' }
